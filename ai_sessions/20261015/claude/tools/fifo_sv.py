def port_name(typ, p):
    nm = fifo.PINS[typ][p]
    if nm.startswith("~"):
        return f"p{p}_{nm[1:].lower()}_n"
    return f"p{p}_{nm.lower()}"


SV_NET = {"VDD": "vdd", "GND": "gnd"}

MEANING = {
    "vdd": "+5V", "gnd": "GND",
}


def board_module(name, stage, chips, wires, find, netname, pinmap, inputs, leds, params):
    """chips: chip ids; inputs: [(net, comment)]; leds: [(port, width, [(index, net, comment)])]."""
    L = fifo.T["en"]
    ends_at = defaultdict(list)  # strip -> wire ids
    for w in wires:
        for e in (w["a"], w["b"]):
            if e[0] == "H":
                ends_at[fifo.strip(e[1], e[2], e[3])].append(w["id"])

    def wire_ids(cid, p):
        b, col, half = fifo.pin_pos(cid, p)
        ids = sorted(set(ends_at.get(("S", b, half, col), [])))
        if not ids:
            return ""
        return ("wire " if len(ids) == 1 else "wires ") + ", ".join(map(str, ids))

    used = sorted({n for n in pinmap.values() if n and n not in ("VDD", "GND") and "." not in n},
                  key=lambda n: list(fifo.NETS).index(n))
    in_nets = [n for n, _ in inputs]
    o = []
    title = "Stage 1 of the build guide, exercise BB8" if stage == 1 else "Stage 2 of the build guide, exercise P3"
    o.append(f"//----------------------------------------------------------------------------\n"
             f"// {name}: {title}.\n// Generated from the breadboard wires by tools/fifo_sv.py.\n"
             f"//----------------------------------------------------------------------------\n")
    o.append(f"module {name}\n")
    if params:
        o.append("# (\n    parameter t_gate = 125,  // 4082\n              t_ff   = 150,  // 4013\n"
                 "              t_add  = 400   // 4008\n)\n")
    o.append("(\n    // OUT pins of the button and clock modules\n")
    plines = []
    for n, c in inputs:
        plines.append((f"    input        {n}", f"// {c}"))
    o.append("".join(f"{a},{' ' * max(1, 26 - len(a))}{b}\n" for a, b in plines))
    o.append("\n    // LEDs\n")
    llines = []
    for port, width, items in leds:
        rng = f"[{width}:1] " if width > 1 else "      "
        llines.append(f"    output {rng}{port}")
    o.append(",\n".join(llines) + "\n);\n\n")
    o.append("    supply1 vdd;\n    supply0 gnd;\n\n")
    for n in used:
        if n in in_nets:
            continue
        meaning = L["meaning"].get(n, "")
        if stage == 1 and n == "pC":
            meaning = "pop button in step with the clock, inverted: SO of A through the temporary wire"
        o.append(f"    wire {n};{' ' * (6 - len(n))}// {meaning}\n")
    o.append("\n")
    for cid in chips:
        typ = fifo.CHIP_TYPES[cid]
        b, lo, hi = fifo.chip_span(cid)
        mod = {"40105": "cd74hc40105", "4013": "cd4013b", "4008": "cd4008b", "4082": "cd4082b"}[typ]
        par = {"4013": " # (.t_pd (t_ff))", "4008": " # (.t_pd (t_add))", "4082": " # (.t_pd (t_gate))"}.get(typ, "")
        if not params:
            par = ""
        inst = "u_" + cid.lower()
        o.append(f"    // {fifo.CHIP_LABEL[cid]}, {L['board'][b]}, columns {lo}-{hi}, pin 1 in {lo}f\n\n")
        o.append(f"    {mod}{par} {inst}\n    (\n")
        rows = []
        for p in range(1, fifo.NPINS[typ] + 1):
            if fifo.NETLIST[cid][p] == "NC":
                continue
            net = pinmap[(cid, p)]
            if net is None or "." in net:
                conn = ""
                note = "not used"
            else:
                conn = SV_NET.get(net, net)
                note = wire_ids(cid, p)
            if stage == 2 and cid == fifo.LC_CHIP and p >= 9:
                led = f"LED {17 - p} of the LED module on C"
                note = f"{note}; {led}" if note and note != "not used" else led
            rows.append((f"        .{port_name(typ, p)}", conn, note))
        w1 = max(len(r[0]) for r in rows)
        w2 = max(len(r[1]) for r in rows)
        for k, (a, c, note) in enumerate(rows):
            comma = "," if k < len(rows) - 1 else " "
            o.append(f"{a.ljust(w1)} ( {c.ljust(w2)} ){comma}" + (f"  // {note}" if note else "") + "\n")
        o.append("    );\n\n")
    o.append("    // LEDs: each one shows the column its leg or header pin is in\n\n")
    for port, width, items in leds:
        for idx, net, c in items:
            lhs = f"{port} [{idx}]" if width > 1 else port
            o.append(f"    assign {lhs.ljust(15)} = {SV_NET.get(net, net)};{' ' * max(1, 6 - len(SV_NET.get(net, net)))}// {c}\n")
        o.append("\n")
    o.append("endmodule\n")
    return "".join(o)


def write_sv(path):
    r = fifo.check()
    wires = r["wires"]
    final = [w for w in wires if w["group"] != "Temporary"]
    find, name, pinmap, probs = fifo.check_wiring(final, list(fifo.CHIP_TYPES))
    assert not probs
    s1 = [w for w in wires if w["stage"] == 1]
    find1, name1, pinmap1, probs1 = fifo.check_wiring(s1, ["U1", "A"], override={("A", 15): fifo.TEMP_WIRE[0]})
    assert not probs1
    mods = {m[0]: m for m in fifo.MODULES}

    def mod_comment(mid):
        b, col = (fifo.pin_pos(*mods[mid][4])[:2] if mods[mid][4] else fifo.POPC_HOLE)
        return f"{fifo.T['en']['mod_desc'][mid]}, OUT in {col}j"

    order = ["clk", "rst", "pushA", "pushB", "popC", "d0", "d1", "d2"]
    inputs2 = [(m, mod_comment(m)) for m in order]
    inputs1 = [(m, mod_comment(m)) for m in order if m in fifo.STAGE1_MODULES]
    leds1 = led_list(find1, name1, 1)
    leds2 = led_list(find, name, 2)
    stage1_chips = ["U1", "A"]
    stage2_chips = ["U1", "U2", "A", "B", "C", "AND", "ADD"]
    text = (HEADER + CHIPS.lstrip("\n") + "\n"
            + board_module("bb8_fifo_demo", 1, stage1_chips, s1, find1, name1, pinmap1, inputs1, leds1, False) + "\n"
            + board_module("p3_fifo_adder", 2, stage2_chips, final, find, name, pinmap, inputs2, leds2, True)
            + TESTBENCH)
    with open(path, "w") as f:
        f.write(text)


def led_list(find, name, stage):
    out = []
    ab = []
    for k in range(1, 9 if stage == 2 else 5):
        net = name.get(find(fifo.strip(fifo.LA_BOARD, fifo.LA_G + k, "h")))
        ab.append((k, net, f"A/B LED module, LED {k}"))
    out.append(("led_ab", 8 if stage == 2 else 4, ab))
    if stage == 2:
        lb, lg = fifo.lc_g()
        c = []
        for k in range(1, 9):
            net = name.get(find(fifo.strip(lb, lg + k, "b")))
            c.append((k, net, f"LED module on C, LED {k}: pin {17 - k} {fifo.PINS['40105'][17 - k]}"))
        out.append(("led_c", 8, c))
        for net, cid, p, colour in fifo.SINGLE_LEDS:
            b, col, half = fifo.pin_pos(cid, p)
            got = name.get(find(fifo.strip(b, col, "j")))
            out.append(("led_" + colour, 1, [(1, got, f"{colour} 5V LED, long leg in {col}j")]))
    return out


